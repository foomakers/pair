import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import ncc from '@vercel/ncc'

const entry = fileURLToPath(new URL('../src/cli/workflow.ts', import.meta.url))
const shipped = fileURLToPath(
  new URL(
    '../../knowledge-hub/dataset/.skills/capability/workflow/scripts/workflow.mjs',
    import.meta.url,
  ),
)
const { values } = parseArgs({ options: { output: { type: 'string', default: shipped } } })
const output = resolve(values.output)
const license = 'licenses.txt'
const { code, assets } = await ncc(entry, {
  esm: true,
  target: 'es2022',
  cache: false,
  quiet: true,
  minify: true,
  transpileOnly: true,
  license,
})
const extraAssets = Object.keys(assets).filter(name => name !== license)
if (extraAssets.length) {
  throw new Error(`Expected a standalone workflow bundle. Extra assets: ${extraAssets.join(', ')}`)
}

const notices = String(assets[license]?.source ?? '').trim()
const licenseComment = notices ? `/*\n${notices.replaceAll('*/', '* /')}\n*/\n` : ''
const header = '// Generated by pnpm --filter @pair/workflows bundle:workflow\n'
await mkdir(dirname(output), { recursive: true })
await writeFile(output, `${header}${licenseComment}${code.trimEnd()}\n`)
